source('R/predict.R'); b <- load_bundle()
p <- jsonlite::fromJSON('examples/request.json',simplifyVector=FALSE)
a <- predict_records(p,b)
stopifnot(length(a$predictions)==1L, a$predictions[[1]]$class %in% b$classes,
          abs(sum(unlist(a$predictions[[1]]$probabilities))-1)<1e-5)
p2<-p;p2$records<-c(p$records,p$records);a2<-predict_records(p2,b)
stopifnot(identical(a$predictions[[1]]$probabilities,a2$predictions[[1]]$probabilities))
expect_bad <- function(x) stopifnot(inherits(tryCatch(predict_records(x,b),input_error=identity),'input_error'))
z<-p;z$records[[1]]$country<-'nicaragua';expect_bad(z)
z<-p;z$records[[1]]$owner_age<- -1;expect_bad(z)
z<-p;z$records[[1]]$Target<-'High';expect_bad(z)
z<-p;z$records[[1]]$owner_age<-'35';expect_bad(z)
z<-p;z$records<-list();expect_bad(z)
z<-p;z$records[[1]]['owner_age']<-list(NULL);predict_records(z,b)
cat('API prediction and input checks passed.\n')
